import { FeatureDefinitionSchema, type FeatureDefinition } from "../schemas.ts";
import { contentHash } from "../hash.ts";

type Draft = Omit<FeatureDefinition, "id"> & { expression: string };

function def(d: Draft): FeatureDefinition & { expression: string; formulaHash: string } {
  const formulaHash = contentHash({
    expression: d.expression,
    lookback: d.lookback,
    timeframe: d.timeframe,
    family: d.family,
  });
  const parsed = FeatureDefinitionSchema.parse({
    ...d,
    id: `feat_${contentHash({ name: d.name, version: d.version }).slice(0, 16)}`,
  });
  return { ...parsed, expression: d.expression, formulaHash };
}

