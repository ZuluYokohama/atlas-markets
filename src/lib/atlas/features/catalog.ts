export const FEATURE_CATALOG = drafts.map(def);

export function catalogByName(name: string) {
  const f = FEATURE_CATALOG.find((x) => x.name === name);
  if (!f) throw new Error(`UNKNOWN_FEATURE: ${name}`);
  return f;
}

export function requiredFamilies(): string[] {
  return [...new Set(FEATURE_CATALOG.map((f) => f.family))];
}
